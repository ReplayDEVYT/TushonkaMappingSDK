# Writes Unity/TushonkaMappingSDK/Assets/TarkovSDK/Editor/TarkovGameTypeTrees.cs: the type trees of the Unity classes the
# SDK's game file reader (TarkovGameFiles.cs) reads, for the game's Unity version. The game's data files are built
# without type trees, so the reader needs them; they come from UnityPy's type tree database (pip install UnityPy).
#   python Tools/GameTypeTrees/dump_typetrees.py
import os
from UnityPy.helpers.Tpk import get_typetree_node, get_common_strings
from UnityPy.helpers.UnityVersion import UnityVersion

VERSION = "2022.3.43f1"
# GameObject, Transform, Material, MeshRenderer, Texture2D, MeshFilter, Mesh, Shader, Rigidbody, MeshCollider,
# BoxCollider, TagManager, Cubemap, TrailRenderer, Light, MonoBehaviour, MonoScript, PhysicMaterial, SphereCollider, CapsuleCollider,
# SkinnedMeshRenderer, BuildSettings, CharacterJoint, ResourceManager, ParticleSystem, ParticleSystemRenderer, LODGroup,
# AudioSource, AudioClip, AssetBundle (the sound importer writes one around a clip)
CLASSES = [1, 4, 21, 23, 28, 33, 43, 48, 54, 64, 65, 78, 82, 83, 89, 96, 108, 114, 115, 120, 134, 135, 136, 137, 141, 142, 144, 147, 198, 199, 205]

version = UnityVersion.from_str(VERSION)
lines = []
for class_id in CLASSES:
    root = get_typetree_node(class_id, version)
    lines.append(f"# {class_id}")
    def walk(node, depth):
        # Unity's meta flags (0x4000 = align after); the sound importer writes them back into the bundles it makes
        lines.append(f"{depth} {node.m_Type.replace(' ', '_')} {node.m_Name.replace(' ', '_')} {node.m_ByteSize} {node.m_MetaFlag or 0} {node.m_Version or 1}")
        for child in node.m_Children:
            walk(child, depth + 1)
    walk(root, 0)

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "..", "Unity", "TushonkaMappingSDK", "Assets", "TarkovSDK", "Editor", "TarkovGameTypeTrees.cs")
with open(out, "w", newline="\n") as f:
    f.write("// <auto-generated>\n")
    f.write(f"// Unity {VERSION} type trees of the classes TarkovGameFiles reads, from UnityPy's type tree database.\n")
    f.write("// Do not edit by hand: regenerate with Tools/GameTypeTrees/dump_typetrees.py.\n")
    f.write("// One node per line: depth, type, name (spaces as _), byte size, meta flags (0x4000 = align after), version.\n")
    f.write("// </auto-generated>\n")
    f.write("namespace TarkovSDK.Editor\n{\n    internal static class TarkovGameTypeTrees\n    {\n        public const string Data = @\"\n")
    f.write("\n".join(lines))
    f.write("\n\";\n\n")
    # Unity's common strings: type tree blobs in asset bundles point into this table for names and types
    common = get_common_strings(version)
    f.write("        // Unity's common type tree strings by offset (asset bundles' type trees refer to them)\n")
    f.write("        public const string CommonStrings = @\"\n")
    f.write("\n".join(f"{offset} {name}" for offset, name in sorted(common.items())))
    f.write("\n\";\n    }\n}\n")
print(out, len(lines))
